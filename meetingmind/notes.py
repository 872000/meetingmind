"""Generate Markdown meeting notes + talk-time chart from a transcript."""

from __future__ import annotations

import os
from datetime import date

import matplotlib

matplotlib.use("Agg")  # headless: no display needed
import matplotlib.pyplot as plt

from . import nlp
from .extract import (
    ActionItem,
    Decision,
    SpeakerStats,
    extract_action_items,
    extract_decisions,
    parse_transcript,
    sentences_with_speakers,
    talk_time,
)


def analyze(raw: str, summary_sentences: int = 5) -> dict:
    """Run the full pipeline; returns a plain-data report dict."""
    utterances = parse_transcript(raw)
    sentences = sentences_with_speakers(utterances)
    summary = nlp.summarize_sentences([s.text for s in sentences], top_n=summary_sentences)
    actions = extract_action_items(utterances)
    decisions = extract_decisions(utterances)
    stats = talk_time(utterances)
    return {
        "utterances": len(utterances),
        "sentences": len(sentences),
        "summary": summary,
        "actions": actions,
        "decisions": decisions,
        "talk_time": stats,
    }


def _fmt_action(a: ActionItem) -> str:
    bits = [f"**{a.assignee}** — {a.text}" if a.assignee else a.text]
    if a.due:
        bits.append(f"(due: {a.due})")
    return "- " + " ".join(bits)


def render_markdown(report: dict, title: str) -> str:
    """Render the analysis report as a Markdown meeting-notes document."""
    lines = [
        f"# Meeting notes — {title}",
        "",
        f"_Generated by MeetingMind on {date.today().isoformat()} · "
        f"{report['utterances']} utterances, {report['sentences']} sentences_",
        "",
        "## Summary",
        "",
    ]
    if report["summary"]:
        for s in report["summary"]:
            lines.append(f"- {s}")
    else:
        lines.append("- _No summary available._")
    lines += ["", "## Action items", ""]
    if report["actions"]:
        for a in report["actions"]:
            lines.append(_fmt_action(a))
    else:
        lines.append("- _None detected._")
    lines += ["", "## Decisions", ""]
    if report["decisions"]:
        for d in report["decisions"]:
            lines.append(f"- {d.text} _(— {d.speaker.title()})_")
    else:
        lines.append("- _None detected._")
    lines += ["", "## Talk time", ""]
    lines.append("| Speaker | Words | Share |")
    lines.append("| --- | ---: | ---: |")
    for st in report["talk_time"]:
        lines.append(f"| {st.speaker.title()} | {st.words} | {st.share:.0%} |")
    lines += [
        "",
        "---",
        "_Heuristic extraction: action items and decisions are found with "
        "hand-written patterns (commitment verbs, 'will/shall', decision phrases). "
        "They can miss reworded commitments or misattribute an owner — "
        "always skim the transcript for anything critical._",
    ]
    return "\n".join(lines) + "\n"


def talk_time_chart(stats: list[SpeakerStats], path: str, title: str = "Talk time by speaker") -> str:
    """Save a bar chart of speaker word-share to `path` (PNG)."""
    speakers = [s.speaker.title() for s in stats]
    shares = [s.share * 100 for s in stats]
    colors = plt.cm.Blues([0.45 + 0.5 * (i / max(1, len(speakers) - 1)) for i in range(len(speakers))])

    fig, ax = plt.subplots(figsize=(8, 4.5))
    bars = ax.barh(speakers, shares, color=colors, edgecolor="#1f3a5f")
    ax.set_xlabel("Share of words (%)")
    ax.set_title(title, fontsize=13, fontweight="bold", pad=12)
    ax.set_xlim(0, max(shares + [10]) * 1.15)
    for bar, share in zip(bars, shares):
        ax.text(bar.get_width() + 0.8, bar.get_y() + bar.get_height() / 2,
                f"{share:.1f}%", va="center", fontsize=10)
    ax.invert_yaxis()
    fig.tight_layout()

    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path


def write_notes(raw: str, title: str, out_dir: str, summary_sentences: int = 5) -> dict[str, str]:
    """Full pipeline: analyze, write Markdown notes + chart PNG. Returns paths."""
    report = analyze(raw, summary_sentences=summary_sentences)
    slug = "".join(c if c.isalnum() else "-" for c in title.lower()).strip("-")
    os.makedirs(out_dir, exist_ok=True)
    md_path = os.path.join(out_dir, f"notes-{slug}.md")
    chart_path = os.path.join(out_dir, f"talktime-{slug}.png")
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(render_markdown(report, title))
    talk_time_chart(report["talk_time"], chart_path, title=f"Talk time — {title}")
    return {"markdown": md_path, "chart": chart_path}
